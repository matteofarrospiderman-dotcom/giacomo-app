"""Plain-text tablature (Ultimate-Guitar style).

Notation key printed in the header::

    h hammer-on   p pull-off   / \\ slide up/down   b bend (7b9)   r release (7b9r7)
    ~ vibrato     x dead note  PM palm mute          (7) tied/held note   <12> harmonic
"""

from __future__ import annotations

from ..guitar.tunings import midi_to_name
from .common import note_index, tech

LEGEND = ("h hammer-on | p pull-off | / \\ slide | b bend | r release | ~ vibrato | x dead | "
          "PM palm mute | (n) held | <n> harmonic")


def _width(ticks: int) -> int:
    # spacing roughly proportional to duration: 16th = 3 chars, 8th = 4, quarter = 6
    if ticks >= 1920:
        return 8
    if ticks >= 960:
        return 6
    if ticks >= 480:
        return 4
    return 3


def _cell(n: dict, tied: bool) -> str:
    if n.get("dead"):
        return "x"
    f = str(n["fret"])
    if tied:
        return f"({f})"
    s = f
    if tech(n, "harmonic"):
        s = f"<{f}>"
    for t in n.get("techniques", []):
        k = t["type"]
        st = t.get("semitones", 1)
        target = int(n["fret"]) + int(round(st))
        if k == "bend":
            s += f"b{target}"
        elif k == "bend_release":
            s += f"b{target}r{n['fret']}"
        elif k == "prebend_release":
            s = f"pb{target}r{n['fret']}"
    if tech(n, "vibrato"):
        s += "~"
    return s


def _prefix(n: dict) -> str:
    if tech(n, "hammer_on"):
        return "h"
    if tech(n, "pull_off"):
        return "p"
    return ""


def render_track(track: dict, title: str, analysis: dict, measures_per_line: int = 4) -> str:
    tun = track["tuning"]
    notes_low_high = tun["notes"]
    n_strings = len(notes_low_high)
    labels = [midi_to_name(p)[:-1] for p in reversed(notes_low_high)]  # string 1 first
    width = max(len(lab) for lab in labels)
    idx = note_index(track)
    lines = [f"{title} – {track['name']}",
             f"Tuning: {tun['name']} ({' '.join(midi_to_name(p) for p in notes_low_high)})"
             + (f"   Capo: {track['capo']}" if track.get("capo") else ""),
             f"Tempo: ~{analysis['rhythm']['bpm']:.0f} BPM   Time: {track['grid']['time_signature'][0]}/"
             f"{track['grid']['time_signature'][1]}   Key: {analysis.get('key', {}).get('name', '?')}",
             f"Legend: {LEGEND}",
             "Generated by TabForge AI – automatic transcription, verify by ear.",
             ""]
    blocks: list[list[str]] = []
    for meas in track["notation"]:
        rows = [""] * n_strings
        pm_row = ""
        slide_pending: dict[int, str] = {}
        for b in meas["beats"]:
            w = _width(b["ticks"])
            cells = [""] * n_strings
            pm = False
            for r in b["notes"]:
                n = idx.get(r["id"])
                if not n or n.get("string") is None:
                    continue
                s = int(n["string"]) - 1
                if s >= n_strings:
                    continue
                c = _cell(n, r["tie"])
                if not r["tie"]:
                    c = slide_pending.pop(s, "") + _prefix(n) + c
                    sl = tech(n, "slide")
                    if sl:
                        slide_pending[s] = "/" if sl.get("direction") == "up" else "\\"
                    if tech(n, "palm_mute"):
                        pm = True
                cells[s] = c
            w = max(w, max(len(c) for c in cells) + 1)
            for s in range(n_strings):
                rows[s] += cells[s].ljust(w, "-") if cells[s] else "-" * w
            pm_row += ("PM" if pm else "").ljust(w)
        blocks.append([pm_row] + rows)
    for i in range(0, len(blocks), measures_per_line):
        chunk = blocks[i: i + measures_per_line]
        lines.append(f"[{i + 1}]")
        pm = " " * (width + 1) + " ".join(" " + b[0] for b in chunk)
        if pm.strip():
            lines.append(pm.rstrip())
        for s in range(n_strings):
            lines.append(labels[s].ljust(width) + "|" + "|".join("-" + b[s + 1] for b in chunk) + "|")
        lines.append("")
    return "\n".join(lines)


def export_text(tracks: list[dict], analysis: dict, title: str) -> str:
    return "\n\n".join(render_track(t, title, analysis) for t in tracks)
